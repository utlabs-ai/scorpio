test('push subscription keeps preferences for the same account and resets them after changing accounts', async () => {
  const w = await worker()
  try {
    const a = await w.person('push-a')
    const b = await w.person('push-b')
    const room = await w.topic(a)
    const endpoint = 'https://fcm.googleapis.com/fcm/send/e1'
    const subscribe = (p) => p.post('/push/subscribe', { endpoint, keys: { p256dh: 'key', auth: 'secret' } })
    const read = () => a.post('/push/preferences/read', { endpoint })

    await expect(await subscribe(a), 200, '"ok":true')
    await expect(await a.post('/push/preferences/write', { endpoint, sound: false, roomId: room, muted: true }), 200, '"sound":false')

    await expect(await subscribe(a), 200, '"ok":true')
    let preferences = await w.json(await read())
    assert.equal(preferences.status, 200)
    assert.equal(preferences.sound, false)
    assert.deepEqual(preferences.mutedRooms, [room])

    await expect(await subscribe(b), 200, '"ok":true')
    await expect(await read(), 404, 'push_subscription_not_found')

    await expect(await subscribe(a), 200, '"ok":true')
    preferences = await w.json(await read())
    assert.equal(preferences.status, 200)
    assert.equal(preferences.sound, true)
    assert.deepEqual(preferences.mutedRooms, [])
  } finally { await w.dispose() }
})

test('stage-one public APIs run before web login and canonical redirect', async () => {
  const w = await worker()
  try {
    await expect(await w.fetch('/oauth/device/code', { method: 'POST', body: '{}' }), 200, '"device_code"')
    await expect(await w.fetch('/oauth/token', { method: 'POST', body: '{}' }), 400, 'unsupported_grant_type')
    await expect(await w.fetch('/billing/creem/webhook', { method: 'POST', body: '{}' }), 401, 'signature')
    const page = await w.fetch('https://other.test/login')
    assert.equal(page.status, 301)
    assert.equal(page.headers.get('location'), `${ORIGIN}/login`)
  } finally { await w.dispose() }
})
