// The lane and the overview over HTTP (docs/api/topics.md "The lane", "The overview"): the agent's own lane, its person's,
// the join's, the overview for a member, and the /r/<id>/view page with the topic page's access.
import assert from 'node:assert/strict'
import test from 'node:test'
import { worker, ORIGIN } from './helpers/worker.mjs'

const w = await worker()
test.after(() => w.dispose())
const kai = await w.person('kai'), mei = await w.person('mei'), zoe = await w.person('zoe'), ann = await w.person('ann')
const priv = await w.topic(kai, '234-567-89A')
const pub = await w.topic(kai, '')
const api = async (p, path, body, role) => w.json(await (body === undefined ? p.api(`/rooms/${priv}${path}`, {}, role) : p.apiPost(`/rooms/${priv}${path}`, body, role)))
const member = async (name) => (await api(kai, '/members', undefined, 'api')).members.find((m) => m.name === name)

test('join with lane= sets it; without, the seat keeps it; the answer and members carry lane, laneBy, laneAt', async () => {
  const joined = await w.json(await kai.apiPost(`/rooms/${priv}/join`, { role: 'api', lane: ' billing ' }))
  assert.equal(joined.lane, 'billing')
  let m = await member('api@kai')
  assert.deepEqual([m.lane, m.laneBy, typeof m.laneAt], ['billing', 'api@kai', 'number'])
  assert.equal((await w.json(await kai.apiPost(`/rooms/${priv}/join`, { role: 'api', resume: true }))).lane, 'billing', 'absent: unchanged')
  assert.equal((await w.json(await kai.apiPost(`/rooms/${priv}/join`, { role: 'api', resume: true, lane: '' }))).lane, 'billing', 'empty: unchanged')
  assert.equal((await w.json(await kai.apiPost(`/rooms/${priv}/join`, { role: 'api', resume: true, lane: 'release' }))).lane, 'release')
  const bad = await w.json(await kai.apiPost(`/rooms/${priv}/join`, { role: 'api', resume: true, lane: 'two words' }))
  assert.equal(bad.error, 'bad_request')
  assert.match(bad.next, /one word of up to 32 characters/)
  const person = (await api(kai, '/members', undefined, 'api')).members.find((x) => x.name === 'kai')
  assert.deepEqual([person.lane, person.laneBy, person.laneAt], [null, null, null], 'every kind has the fields')
})

test('POST /lane: the agent sets its own, clears it with "", a bad word is refused', async () => {
  const set = await api(kai, '/lane', { lane: '日历' }, 'api')
  assert.equal(set.status, 200)
  assert.deepEqual([set.roomId, set.name, set.lane, set.laneBy, typeof set.laneAt], [priv, 'api@kai', '日历', 'api@kai', 'number'])
  assert.equal((await member('api@kai')).lane, '日历')
  const bad = await api(kai, '/lane', { lane: 'a|b' }, 'api')
  assert.equal(bad.status, 400)
  assert.equal(bad.error, 'bad_request')
  const cleared = await api(kai, '/lane', { lane: '' }, 'api')
  assert.equal(cleared.lane, null)
  assert.equal((await member('api@kai')).lane, null)
  assert.equal((await api(ann, '/lane', { lane: 'x' }, 'x')).error, 'not_member')
})

test('POST /r/<id>/lane: the agent\'s own person may, for a left agent too; another account and a non-agent are refused', async () => {
  await mei.web(`/r/${priv}/enter`, { method: 'POST', headers: { origin: ORIGIN, 'content-type': 'application/json' }, body: JSON.stringify({ code: '234-567-89A' }) })
  const ok = await w.json(await kai.post(`/r/${priv}/lane`, { name: 'api@kai', lane: 'web' }))
  assert.deepEqual([ok.status, ok.name, ok.lane, ok.laneBy], [200, 'api@kai', 'web', 'kai'])
  assert.deepEqual([(await member('api@kai')).lane, (await member('api@kai')).laneBy], ['web', 'kai'])
  const other = await w.json(await mei.post(`/r/${priv}/lane`, { name: 'api@kai', lane: 'x' }))
  assert.equal(other.status, 403)
  assert.equal(other.error, 'forbidden')
  assert.match(other.next, /Only kai, whose agent api@kai is, can change its lane/)
  const notAgent = await w.json(await kai.post(`/r/${priv}/lane`, { name: 'mei', lane: 'x' }))
  assert.equal(notAgent.status, 400)
  assert.equal((await w.json(await kai.post(`/r/${priv}/lane`, { name: 'api@kai', lane: 'bad word' }))).error, 'bad_request')
  assert.equal((await w.json(await ann.post(`/r/${priv}/lane`, { name: 'api@kai', lane: 'x' }))).error, 'not_member')
  // the agent leaves: its person can still place it (the role card cannot be changed then)
  await kai.apiPost(`/rooms/${priv}/leave`, {}, 'api')
  const left = await w.json(await kai.post(`/r/${priv}/lane`, { name: 'api@kai', lane: 'release' }))
  assert.equal(left.status, 200)
  assert.equal((await w.json(await kai.post(`/r/${priv}/roleCard`, { name: 'api@kai', roleCard: 'x' }))).error, 'bad_request')
  await w.join(kai, priv, 'api')
  assert.equal((await member('api@kai')).lane, 'release', 'a join without lane leaves the person\'s choice')
})

test('GET /overview: a member reads the 7-day counts, pairs, deliveries and lanes; a non-member is refused', async () => {
  await w.join(kai, priv, 'pm')
  await w.join(mei, priv, 'docs')
  await api(kai, '/lane', { lane: 'release' }, 'pm')
  const opened = await api(kai, '/send', { text: '@api@kai build it', add: 'Build it', to: 'api@kai' }, 'pm')
  assert.ok(opened.item?.id, JSON.stringify(opened))
  await api(kai, '/send', { text: '@api@kai more' }, 'pm')
  await api(kai, '/send', { text: '@pm@kai built', done: opened.item.id }, 'api')
  await w.json(await kai.post(`/r/${priv}/send`, { text: '@api@kai @pm@kai thanks' }))
  await w.json(await mei.post(`/r/${priv}/send`, { text: 'hello all' }))
  const o = await api(kai, '/overview', undefined, 'api')
  assert.equal(o.status, 200)
  assert.equal(o.roomId, priv)
  assert.equal(o.until - o.since, 7 * 86_400_000)
  assert.equal(o.messages, 5)
  const by = Object.fromEntries(o.agents.map((a) => [a.name, a]))
  assert.deepEqual(by['api@kai'], { name: 'api@kai', lane: 'release', activity: 1 + 3 + 10, sent: 1, mentioned: 3, delivered: 1 })
  assert.deepEqual(by['pm@kai'], { name: 'pm@kai', lane: 'release', activity: 2 + 2, sent: 2, mentioned: 2, delivered: 0 })
  assert.deepEqual(by['docs@mei'], { name: 'docs@mei', lane: null, activity: 0, sent: 0, mentioned: 0, delivered: 0 })
  assert.deepEqual(o.people, [{ name: 'kai', sent: 1, mentioned: 0 }, { name: 'mei', sent: 1, mentioned: 0 }])
  assert.deepEqual(o.pairs, [{ a: 'api@kai', b: 'pm@kai', n: 3 }, { a: 'api@kai', b: 'kai', n: 1 }, { a: 'kai', b: 'pm@kai', n: 1 }])
  assert.deepEqual(o.scheduled, [])
  assert.deepEqual(o.lanes.map((l) => [l.lane, l.activity, l.stacked, l.agents]), [['release', 18, true, ['api@kai', 'pm@kai']], [null, 0, true, ['docs@mei']]])
  assert.equal((await api(ann, '/overview', undefined, 'x')).error, 'not_member')
})

test('the page /r/<id>/view: a member, a viewer of a public topic, the passcode form and back, sign-in', async () => {
  const page = (p, r, lang = 'zh') => p.web(`/r/${r}/view`, { headers: { cookie: `${p.cookie}; lang=${lang}` } })
  const mine = await page(kai, priv)
  assert.equal(mine.status, 200)
  const html = await mine.text()
  for (const s of ['Route test topic · 全局图 · 最近 7 天', '返回主题', '>方向<', '>在做<', '>等你<', '>消息<', '线粗 = 互 @ 次数 · 方块 = 开着的任务', '/static/gv.js', '/static/gv.css', 'id="gv-board"', 'id="item-panel"']) assert.ok(html.includes(s), s)
  const boot = JSON.parse(/<script type="application\/json" id="boot">([^<]*)<\/script>/.exec(html)[1])
  assert.equal(boot.me, 'kai')
  assert.equal(boot.member, true)
  assert.equal(boot.overview.roomId, priv)
  assert.ok(boot.overview.agents.some((a) => a.name === 'api@kai'))
  assert.equal(boot.S.gv.lanes, '方向')
  // a signed-in viewer of a public topic: the page, read only, English words
  const v = await page(zoe, pub, 'en')
  assert.equal(v.status, 200)
  const vh = await v.text()
  assert.ok(vh.includes('Route test topic · Overview · Last 7 days') && vh.includes('No agent spoke here in the last 7 days'))
  const vb = JSON.parse(/<script type="application\/json" id="boot">([^<]*)<\/script>/.exec(vh)[1])
  assert.equal(vb.member, false)
  assert.deepEqual(vb.overview.agents, [])
  assert.deepEqual(vb.overview.people, [], 'a viewer is not a node on the map')
  // a signed-in non-member of a private topic: the passcode form, then back here
  const form = await page(ann, priv)
  const fh = await form.text()
  assert.ok(fh.includes(`action="/r/${priv}/enter"`) && fh.includes(`name="next" value="/r/${priv}/view"`))
  assert.doesNotMatch(fh, /Route test topic/)
  const entered = await ann.web(`/r/${priv}/enter`, { method: 'POST', headers: { origin: ORIGIN, 'content-type': 'application/x-www-form-urlencoded', accept: 'text/html' }, body: `code=234-567-89A&next=${encodeURIComponent(`/r/${priv}/view`)}` })
  assert.equal(entered.status, 303)
  assert.equal(entered.headers.get('location'), `/r/${priv}/view`)
  assert.equal((await page(ann, priv)).status, 200)
  // signed out: to sign-in and back
  const out = await w.fetch(`/r/${priv}/view`)
  assert.equal(out.status, 303)
  assert.equal(out.headers.get('location'), `/login?next=${encodeURIComponent(`/r/${priv}/view`)}`)
})
